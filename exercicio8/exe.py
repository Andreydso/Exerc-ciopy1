#8. Receba o valor de um depósito em poupança. Calcule e mostre o valor após 1 mês de aplicação sabendo que rende 1,3% a. m.
poupanca = int(input("Digite o valor depitado na poupança: R$"))
renda:int = poupanca + poupanca * 0.015
print(f"A renda do valor depositado depois de 1 mês será de: R${renda}")
